import { describe, it, expect } from 'vitest'
import { isBreaking, matchMacro } from './macro.js'

describe('matchMacro — 주체 + 행위 조합', () => {
  it.each([
    // 실측 제목(2026-10-12~13 수집분)
    ['[속보] 코스피 매도 사이드카 발동…지수 6100 하회', 'market:코스피:사이드카'],
    ['코스피·코스닥, 연이틀 급락세…장초반 3~4%대 하락(종합)', 'market:코스피:급변'],
    ['美태평양사령부 "北 탄도미사일 2발 발사…동맹과 긴밀 협의"', 'geo:북한:미사일'],
    ['사우디 수도서 3차례 폭발음…연합군 "후티 탄도미사일 요격"(종합)', 'geo:후티:미사일'],
    ['트럼프 \'에너지 휴전\' 발표에도 러 공습 계속…국제유가 2% 상승', 'geo:러시아:공습'],
    // 스펙 §3 의 예
    ['트럼프, 中에 100% 추가 관세 부과 발표', 'trade:미국:관세'],
    ['美연준, 기준금리 0.25%p 인하', 'rates:연준:금리'],
    ['한은, 기준금리 연 2.50%로 동결', 'rates:한은:금리'],
    ['이스라엘, 가자지구 공습 재개', 'geo:이스라엘:공습'],
  ])('%s → %s', (title, key) => {
    expect(matchMacro(title)?.key).toBe(key)
  })

  it.each([
    ['트럼프, 그리스 美대사 \'손절\' 검토…해임 질문에 "살펴보는 중"'],
    ['트럼프 "아시아 방문 중 北 김정은 만날 수도"'],
    ['美연준 해맥 "금리 조정 미루면 위험…소폭·신속 대응 바람직"'],
    ['카카오뱅크, AI가 목표 달성 조언하는 적금 출시…최대 5% 금리'],
  ])('행위가 없으면 통과시키지 않는다 — %s', (title) => {
    expect(matchMacro(title)).toBeNull()
  })

  describe('한 글자 약칭·흔한 낱말의 오탐을 막는다', () => {
    // 제목마다 **가드가 없으면 실제로 잘못 잡히는** 행위를 넣었다 — 행위가 없는 제목은
    // 가드가 있든 없든 null 이라 아무것도 검증하지 않는다(변이 테스트로 확인).
    it.each([
      ['北京 찾은 러 외무장관…우크라 휴전 논의', 'geo:러시아:휴전'], // 北京 = 베이징
      ['北美 지역 미사일 방어망 구축', null], // 北美 = 북미
      ['中企 수출 급감…관세 부담 호소', null], // 中企 = 중소기업
      ['EUV 장비 수출통제 강화 검토', null],
      ['유가증권시장 급락 마감', null],
      ['유가족 지원금 신청 급증', null],
      ['다우기술 주가 급등', null],
      ['전쟁이란 무엇인가…석학 대담', null],
    ])('%s → %s', (title, key) => {
      expect(matchMacro(title)?.key ?? null).toBe(key)
    })

    it('정전은 휴전으로 보지 않는다 — 정전 사고가 더 흔하다', () => {
      expect(matchMacro('이란 수도 대규모 정전…원인 조사')).toBeNull()
    })

    it('달러의 "러"는 러시아가 아니다', () => {
      expect(matchMacro('달러 강세에 원화 급락…전쟁 우려 재부각')?.key ?? '').not.toContain('러시아')
    })
  })

  it('무역이 지정학보다 앞선다 — "美中 무역전쟁" 은 전쟁이 아니라 무역 사건이다', () => {
    expect(matchMacro('美中 무역전쟁 재점화')?.key).toBe('trade:미국:무역전쟁')
  })

  it('공백 유무와 무관하게 행위를 찾는다', () => {
    expect(matchMacro('연준 금리 인하 단행')?.key).toBe('rates:연준:금리')
    expect(matchMacro('연준 금리인하 단행')?.key).toBe('rates:연준:금리')
  })

  it('방향이 다른 같은 사건은 같은 키로 모인다 — 위치로 짝을 맞추지 않아 방향이 틀리게 잡힌다', () => {
    // 실측: 코스피는 하락인데 뒤의 "유가 급등" 이 행위로 잡혔다.
    expect(matchMacro('코스피 장 초반부터 4%대 하락…中 CXMT 충격·유가 급등 이중 악재')?.key)
      .toBe(matchMacro('코스피, 장 초반 4% 넘게 급락')?.key)
    expect(matchMacro('한은, 기준금리 동결')?.key).toBe(matchMacro('한은, 기준금리 인하')?.key)
  })

  it('국가명 앞이 문장부호면 국가로 본다 — "美·이란"', () => {
    expect(matchMacro('美·이란 교전 격화')?.key).toBe('geo:이란:전쟁')
  })
})

describe('isBreaking', () => {
  it.each([
    ['[속보] 코스피 매도 사이드카 발동', true],
    ['[1보] 北, 탄도미사일 발사', true],
    ['  [긴급] 연준 긴급 금리 인하', true],
    ['코스피 급락 [속보]', false], // 머리표는 앞에 온다 — 본문 인용이 아니다
    ['[특징주] 에이피알 11% 급락', false],
  ])('%s → %s', (title, expected) => {
    expect(isBreaking(title)).toBe(expected)
  })
})
